#!/usr/bin/env python3
"""Synchronize registered sing-box domain rulesets as Clash classical YAML."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
FIELDS = {"domain": "DOMAIN", "domain_keyword": "DOMAIN-KEYWORD", "domain_suffix": "DOMAIN-SUFFIX"}
MAX_BYTES = 2 * 1024 * 1024


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate JSON key: {key}")
        result[key] = value
    return result


def parse_source(raw):
    if len(raw) > MAX_BYTES:
        raise ValueError("Source exceeds the size limit")
    return json.loads(raw, object_pairs_hook=unique_object)


def load_registry(path):
    data = parse_source(path.read_bytes())
    if not isinstance(data, dict) or set(data) != {"version", "rulesets"} or type(data["version"]) is not int or data["version"] != 1:
        raise ValueError("Unsupported registry schema")
    if not isinstance(data["rulesets"], list) or not data["rulesets"]:
        raise ValueError("Registry must contain at least one ruleset")
    names = set()
    for entry in data["rulesets"]:
        if not isinstance(entry, dict) or set(entry) != {"name", "url", "license"}:
            raise ValueError("Each registry entry requires name, url and license")
        name, url, license_name = entry["name"], entry["url"], entry["license"]
        if not isinstance(name, str) or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]{0,63}", name):
            raise ValueError("Ruleset names must be safe ASCII filenames")
        if name.casefold() in names:
            raise ValueError(f"Duplicate or case-colliding ruleset name: {name}")
        names.add(name.casefold())
        if not isinstance(url, str) or any(c.isspace() or ord(c) < 32 for c in url):
            raise ValueError(f"Invalid source URL for {name}")
        parsed = urllib.parse.urlsplit(url)
        if parsed.scheme != "https" or not parsed.hostname or parsed.username is not None or parsed.password is not None or parsed.fragment:
            raise ValueError(f"Source URL for {name} must use HTTPS without credentials or fragments")
        if not isinstance(license_name, str) or not re.fullmatch(r"[A-Za-z0-9.+-]+", license_name):
            raise ValueError(f"Invalid upstream license identifier for {name}")
    return data["rulesets"]


def convert(data, source_url="", license_name=""):
    if not isinstance(data, dict) or set(data) != {"version", "rules"}:
        raise ValueError("Unexpected source root fields")
    if type(data["version"]) is not int or data["version"] != 2:
        raise ValueError("Only source schema version 2 is supported")
    if not isinstance(data["rules"], list) or not data["rules"]:
        raise ValueError("Source must contain a nonempty rules list")
    payload = []
    for rule in data["rules"]:
        if not isinstance(rule, dict) or not rule or set(rule) - set(FIELDS):
            raise ValueError("Supported fields: domain, domain_keyword, domain_suffix; refusing partial conversion")
        for field, values in rule.items():
            if isinstance(values, str):
                values = [values]
            if not isinstance(values, list) or not values:
                raise ValueError(f"{field} must be a nonempty list")
            for value in values:
                if not isinstance(value, str) or not value or any(c.isspace() or ord(c) < 32 or c == "," for c in value):
                    raise ValueError(f"Invalid {field} value")
                if field == "domain_suffix" and value.startswith("."):
                    raise ValueError("Leading-dot suffixes require a separate exact-semantics conversion")
                payload.append(f"{FIELDS[field]},{value}")
    text = (
        "# Generated by scripts/sync_rulesets.py; do not edit manually.\n"
        f"# Source: {source_url}\n"
        f"# Upstream license: {license_name}; preserve the applicable license notice.\n"
        "payload:\n"
        + "".join(f"  - {json.dumps(rule, ensure_ascii=False)}\n" for rule in payload)
    )
    return text, len(payload)


class HTTPSRedirectHandler(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, request, fp, code, msg, headers, newurl):
        if urllib.parse.urlsplit(newurl).scheme != "https":
            raise ValueError("Source redirect must remain HTTPS")
        return super().redirect_request(request, fp, code, msg, headers, newurl)


def download(url):
    request = urllib.request.Request(url, headers={"User-Agent": "zzxjohn-clash-rules-sync"})
    opener = urllib.request.build_opener(HTTPSRedirectHandler())
    for attempt in range(3):
        try:
            with opener.open(request, timeout=30) as response:
                return response.read(MAX_BYTES + 1)
        except (urllib.error.URLError, TimeoutError):
            if attempt == 2:
                raise
            time.sleep(2 ** attempt)


def prepare_outputs(entries, reader):
    outputs = {}
    counts = {}
    for entry in entries:
        name = entry["name"]
        try:
            data = parse_source(reader(entry))
            yaml_text, count = convert(data, entry["url"], entry["license"])
        except (ValueError, OSError, urllib.error.URLError) as error:
            raise ValueError(f"{name}: {error}") from error
        normalized = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
        provenance = {
            "name": name,
            "source_url": entry["url"],
            "source_version": data["version"],
            "normalized_source_sha256": hashlib.sha256(normalized.encode()).hexdigest(),
            "output_sha256": hashlib.sha256(yaml_text.encode()).hexdigest(),
            "rule_count": count,
            "upstream_license": entry["license"],
        }
        outputs.update({
            f"rules/{name}.yaml": yaml_text,
            f"sources/{name}.json": normalized,
            f"sources/{name}.provenance.json": json.dumps(provenance, indent=2) + "\n",
        })
        counts[name] = count
    return outputs, counts


def write_outputs(root, outputs):
    changed = []
    for relative, text in outputs.items():
        target = root / relative
        if target.exists() and target.read_text(encoding="utf-8") == text:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary = target.with_suffix(target.suffix + ".tmp")
        temporary.write_text(text, encoding="utf-8")
        temporary.replace(target)
        changed.append(relative)
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path, default=ROOT / "rulesets.json")
    parser.add_argument("--source-dir", type=Path, help="Offline snapshots: NAME.json for every registered set")
    parser.add_argument("--source-file", type=Path, help="Legacy offline override; only valid for a single registered set")
    parser.add_argument("--output-root", type=Path, default=ROOT)
    args = parser.parse_args()
    entries = load_registry(args.registry)
    if args.source_file and (args.source_dir or len(entries) != 1):
        raise ValueError("--source-file requires one registered set and no --source-dir")
    def reader(entry):
        if args.source_file:
            return args.source_file.read_bytes()
        if args.source_dir:
            return (args.source_dir / f"{entry['name']}.json").read_bytes()
        return download(entry["url"])
    outputs, counts = prepare_outputs(entries, reader)
    changed = write_outputs(args.output_root, outputs)
    print(f"Validated {len(counts)} ruleset(s), {sum(counts.values())} rules; updated {len(changed)} file(s).")
    for name, count in counts.items():
        print(f"  {name}: {count} rules")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, urllib.error.URLError) as error:
        print(f"Sync failed: {error}", file=sys.stderr)
        sys.exit(1)
