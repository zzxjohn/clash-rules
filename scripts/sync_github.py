#!/usr/bin/env python3
"""Convert the supported sing-box GitHub rules into a classical provider."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import time
import urllib.error
import urllib.request

SOURCE_URL = "https://raw.githubusercontent.com/senshinya/singbox_ruleset/main/rule/GitHub/GitHub.json"
ROOT = Path(__file__).resolve().parents[1]
FIELDS = {"domain_keyword": "DOMAIN-KEYWORD", "domain_suffix": "DOMAIN-SUFFIX"}
MAX_BYTES = 2 * 1024 * 1024


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate JSON key: {key}")
        result[key] = value
    return result


def parse_source(raw):
    if len(raw) > MAX_BYTES:
        raise ValueError("Source exceeds the size limit")
    return json.loads(raw, object_pairs_hook=unique_object)


def convert(data):
    if not isinstance(data, dict) or set(data) != {"version", "rules"}:
        raise ValueError("Unexpected source root fields")
    if type(data["version"]) is not int or data["version"] != 2:
        raise ValueError("Only source schema version 2 is supported")
    if not isinstance(data["rules"], list) or not data["rules"]:
        raise ValueError("Source must contain a nonempty rules list")
    payload = []
    for rule in data["rules"]:
        if not isinstance(rule, dict) or not rule or set(rule) - set(FIELDS):
            raise ValueError("Unsupported rule fields; refusing a partial conversion")
        for field, values in rule.items():
            if not isinstance(values, list) or not values:
                raise ValueError(f"{field} must be a nonempty list")
            for value in values:
                if not isinstance(value, str) or not value or any(
                    c.isspace() or ord(c) < 32 or c == "," for c in value
                ):
                    raise ValueError(f"Invalid {field} value")
                payload.append(f"{FIELDS[field]},{value}")
    text = (
        "# Generated by scripts/sync_github.py; do not edit manually.\n"
        f"# Source: {SOURCE_URL}\n"
        "# Upstream license: GPL-3.0; see LICENSE.\n"
        "payload:\n"
        + "".join(f"  - {json.dumps(rule, ensure_ascii=False)}\n" for rule in payload)
    )
    return text, len(payload)


def download():
    request = urllib.request.Request(SOURCE_URL, headers={"User-Agent": "zzxjohn-clash-rules-sync"})
    for attempt in range(3):
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                return response.read(MAX_BYTES + 1)
        except (urllib.error.URLError, TimeoutError):
            if attempt == 2:
                raise
            time.sleep(2 ** attempt)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-file", type=Path, help="Use a local source for offline validation")
    parser.add_argument("--output-root", type=Path, default=ROOT)
    args = parser.parse_args()
    raw = args.source_file.read_bytes() if args.source_file else download()
    data = parse_source(raw)
    yaml_text, count = convert(data)  # Validate everything before touching any output.
    normalized = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    provenance = {
        "source_url": SOURCE_URL,
        "source_version": data["version"],
        "normalized_source_sha256": hashlib.sha256(normalized.encode()).hexdigest(),
        "output_sha256": hashlib.sha256(yaml_text.encode()).hexdigest(),
        "rule_count": count,
        "upstream_license": "GPL-3.0",
    }
    outputs = {
        "rules/GitHub.yaml": yaml_text,
        "sources/GitHub.json": normalized,
        "sources/GitHub.provenance.json": json.dumps(provenance, indent=2) + "\n",
    }
    changed = []
    for relative, text in outputs.items():
        target = args.output_root / relative
        if target.exists() and target.read_text(encoding="utf-8") == text:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary = target.with_suffix(target.suffix + ".tmp")
        temporary.write_text(text, encoding="utf-8")
        temporary.replace(target)
        changed.append(relative)
    print(f"Validated {count} rules; updated {len(changed)} file(s).")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, urllib.error.URLError) as error:
        print(f"Sync failed: {error}", file=sys.stderr)
        sys.exit(1)
